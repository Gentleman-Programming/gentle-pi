#!/usr/bin/env node
// Generates lib/gentle-ai-required-floor.generated.ts from the checked-in
// gentle-ai semantic capability snapshot, release lock, and hand-authored
// native-cli-history. See design.md D7 ("Generators: derived data, frozen
// floor, visible removals").
//
// Two independent floors are generated here, with two different tolerances:
//
//   REQUIRED_OPERATIONS / REQUIRED_GATES / REQUIRED_PROJECTIONS
//     Monotone regeneration. `--write` may ADD a name the snapshot newly
//     advertises. A name that was previously required and disappears from
//     the snapshot's advertised surface makes generation FAIL naming it --
//     never a silent shrink. To retire a requirement, a human edits the
//     checked-in generated file directly (deleting the entry), which is
//     itself the visible signal a reviewer needs; the next --write then
//     continues forward from that smaller, human-approved baseline.
//
//   NATIVE_CLI_CONTRACTS
//     The 12 historical rows in capabilities/native-cli-history.json (every
//     version strictly older than the currently pinned one) are frozen input
//     data, copied verbatim -- they describe already-released immutable
//     versions and are never recomputed. The row for the CURRENTLY PINNED
//     version is always recomputed: 13 of its 17 columns derive from the
//     snapshot's `operations[]` via a `review.<op>` -> column map (an
//     operation with no column entry at all fails generation, naming it);
//     the remaining 4 envelope columns (mode/riskEvidence/hint/delivery) have
//     no snapshot signal and come from native-cli-history.json's
//     `envelopeFlags` for that version, which MUST be present.

import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const OUTPUT_RELATIVE_PATH = "lib/gentle-ai-required-floor.generated.ts";
const SNAPSHOT_RELATIVE_PATH = "capabilities/review-integration-v2.semantic.json";
const HISTORY_RELATIVE_PATH = "capabilities/native-cli-history.json";
const LOCK_RELATIVE_PATH = "capabilities/gentle-ai-release.lock.json";
const HEADER = "// Generated by scripts/build-gentle-ai-baselines.mjs. Do not edit.\n";

// Pi's own decision about which advertised mandatory feature names it has
// client decode logic for. Deliberately hand-authored here rather than
// derived from the snapshot (a provider superset must never silently become
// Pi's requirement) or from lib/review-integration-v2.ts's own constant (a
// generator that read its consumer's hand-authored answer to grade that
// exact answer would prove nothing). Supporting a new mandatory feature needs
// new decoder code first, then a deliberate edit to this list -- it is never
// auto-added.
export const PI_SUPPORTED_MANDATORY_FEATURES = Object.freeze([
	"compact_v2_authority",
	"exact_receipt_replay",
	"five_delivery_gates",
	"immutable_snapshot",
	"legacy_v1_target_scoped_read_only",
	"repository_independent_capabilities",
	"restart_safe_projection",
	"sdd_receipt_binding",
	"target_scoped_status",
	"uniform_failure_envelope",
]);

// review.<op> -> NativeCliCapability column. `null` marks an operation Pi has
// deliberately decided is not a version-gated boolean capability: either the
// capabilities-negotiation call itself (`review.capabilities`), or an
// operation whose availability is already proven by a successful negotiated
// `review.start`/`review.finalize` exchange rather than a separate flag
// (`review.repair`, `review.retry_final_verification`). An operation absent
// from this map entirely -- not even as an explicit `null` -- is unmapped and
// fails generation.
export const OPERATION_COLUMN_MAP = Object.freeze({
	"review.start": "start",
	"review.finalize": "finalize",
	"review.validate": "validate",
	"review.bind_sdd": "bindSdd",
	"review.status": "status",
	"review.capabilities": null,
	"review.repair": null,
	"review.retry_final_verification": null,
});

// Legacy CLI columns that predate the negotiated review-integration/v2
// `operations[]` surface entirely. The semantic snapshot never advertises
// them, so they carry forward unchanged from the immediately preceding
// frozen historical row -- there is no live signal to regenerate them from.
export const CARRY_FORWARD_COLUMNS = Object.freeze([
	"sddStatus", "inventory", "reclaim", "recover", "abandon",
	"quarantineLegacy", "reconcileAuthority", "repairLegacyAlias",
]);
export const CAPABILITY_COLUMNS = Object.freeze([
	"start", "finalize", "validate", "bindSdd", "sddStatus", "status",
	"inventory", "reclaim", "recover", "abandon", "quarantineLegacy",
	"reconcileAuthority", "repairLegacyAlias",
]);
export const ENVELOPE_COLUMNS = Object.freeze(["mode", "riskEvidence", "hint", "delivery"]);

export function assertNoTrailingWhitespace(content, label) {
	const line = content.split("\n").findIndex((value) => /[ \t]+$/.test(value));
	if (line >= 0) throw new Error(`${label} contains trailing whitespace on line ${line + 1}`);
}

// `--write` may only ever grow the returned set relative to `previousRequired`.
// A name present in `previousRequired` but absent from `advertised` is a
// regression: generation fails naming it rather than silently dropping it.
export function monotoneFloor(previousRequired, advertised, label) {
	const missing = previousRequired.filter((name) => !advertised.includes(name));
	if (missing.length > 0) {
		throw new Error(
			`${label}: ${missing.join(", ")} disappeared from the snapshot's required block. ` +
			`A removal must be a hand-authored deletion from ${OUTPUT_RELATIVE_PATH} -- never an ` +
			`automatic --write. Edit the checked-in generated file to remove the entries, then re-run --write.`,
		);
	}
	return [...new Set([...previousRequired, ...advertised])].sort();
}

export function assertMandatoryFeaturesSupported(advertisedMandatoryNames, supported = PI_SUPPORTED_MANDATORY_FEATURES) {
	const unsupported = advertisedMandatoryNames.filter((name) => !supported.includes(name));
	if (unsupported.length > 0) {
		throw new Error(
			`gentle-ai advertises mandatory feature(s) with no gentle-pi client support: ${unsupported.join(", ")}. ` +
			`A mandatory feature needs client decoder work before it can be added to PI_SUPPORTED_MANDATORY_FEATURES ` +
			`in scripts/build-gentle-ai-baselines.mjs -- it is never auto-added.`,
		);
	}
}

// Computes the NATIVE_CLI_CONTRACTS row for exactly one version (the
// currently pinned one). `previousRow` supplies CARRY_FORWARD_COLUMNS values;
// `knownRow`, if present, is the historically-recorded row for this exact
// version (native-cli-history.json's own entry, when this version already
// has one) and is cross-checked against the freshly derived row so a
// disagreement is never silently accepted.
export function deriveCapabilityRow({ version, advertisedOperations, envelopeFlags, previousRow, knownRow, operationColumnMap = OPERATION_COLUMN_MAP }) {
	if (envelopeFlags === undefined) {
		throw new Error(
			`gentle-ai ${version} has no envelopeFlags entry in ${HISTORY_RELATIVE_PATH}. ` +
			`Append one (mode/riskEvidence/hint/delivery) before generating this version's row.`,
		);
	}
	for (const flag of ENVELOPE_COLUMNS) {
		if (typeof envelopeFlags[flag] !== "boolean") {
			throw new Error(`gentle-ai ${version} envelopeFlags.${flag} in ${HISTORY_RELATIVE_PATH} must be a boolean`);
		}
	}

	const columnForOperation = operationColumnMap;
	for (const operation of advertisedOperations) {
		if (!(operation in columnForOperation)) {
			throw new Error(`gentle-ai ${version} advertises operation "${operation}" with no NativeCliCapability column. Add the column and its decoder in lib/native-review-cli.ts, then re-run --write.`);
		}
	}
	const operationForColumn = new Map();
	for (const [operation, column] of Object.entries(columnForOperation)) {
		if (column !== null) operationForColumn.set(column, operation);
	}

	const capabilities = {};
	for (const column of CAPABILITY_COLUMNS) {
		if (operationForColumn.has(column)) {
			capabilities[column] = advertisedOperations.includes(operationForColumn.get(column));
		} else if (CARRY_FORWARD_COLUMNS.includes(column)) {
			if (previousRow === undefined || typeof previousRow[column] !== "boolean") {
				throw new Error(`gentle-ai ${version} has no prior frozen row to carry column "${column}" forward from. Add a ${HISTORY_RELATIVE_PATH} entry for the immediately preceding version first.`);
			}
			capabilities[column] = previousRow[column];
		} else {
			throw new Error(`internal error: capability column "${column}" is neither operation-mapped nor carry-forward`);
		}
	}

	const row = { ...capabilities, ...envelopeFlags };
	if (knownRow !== undefined) {
		const disagreeing = [...CAPABILITY_COLUMNS, ...ENVELOPE_COLUMNS].filter((column) => knownRow[column] !== row[column]);
		if (disagreeing.length > 0) {
			throw new Error(`gentle-ai ${version} freshly derived row disagrees with its ${HISTORY_RELATIVE_PATH} record on: ${disagreeing.join(", ")}. Investigate before writing.`);
		}
	}
	return row;
}

function jsonObjectLiteral(value) {
	return JSON.stringify(value);
}

export function renderGeneratedFloorModule({ requiredOperations, requiredGates, requiredProjections, historicalRows, currentVersion, currentRow, currentNotes }) {
	const lines = [HEADER.trimEnd()];
	lines.push("");
	lines.push("export const REQUIRED_OPERATIONS = Object.freeze(" + jsonObjectLiteral(requiredOperations) + ");");
	lines.push("export const REQUIRED_GATES = Object.freeze(" + jsonObjectLiteral(requiredGates) + ");");
	lines.push("export const REQUIRED_PROJECTIONS = Object.freeze(" + jsonObjectLiteral(requiredProjections) + ");");
	lines.push("");
	lines.push("export const NATIVE_CLI_CONTRACTS = Object.freeze({");
	const rows = [...historicalRows, { version: currentVersion, row: currentRow, notes: currentNotes }].sort((a, b) => a.version.localeCompare(b.version, undefined, { numeric: true }));
	for (const entry of rows) {
		for (const note of entry.notes ?? []) lines.push(`\t// ${note}`);
		lines.push(`\t"${entry.version}": Object.freeze(${jsonObjectLiteral(entry.row)}),`);
	}
	lines.push("});");
	lines.push("export type NativeCliCapability = keyof (typeof NATIVE_CLI_CONTRACTS)[keyof typeof NATIVE_CLI_CONTRACTS];");
	lines.push("");
	return lines.join("\n");
}

export function parseRequiredFloorModule(source) {
	const extract = (name) => {
		const match = source.match(new RegExp(`export const ${name} = Object\\.freeze\\((\\[[\\s\\S]*?\\])\\);`));
		return match === null ? [] : JSON.parse(match[1]);
	};
	return {
		requiredOperations: extract("REQUIRED_OPERATIONS"),
		requiredGates: extract("REQUIRED_GATES"),
		requiredProjections: extract("REQUIRED_PROJECTIONS"),
	};
}

async function readJson(relativePath) {
	return JSON.parse(await readFile(join(root, relativePath), "utf8"));
}

async function readPreviousRequiredFloor() {
	try {
		const source = await readFile(join(root, OUTPUT_RELATIVE_PATH), "utf8");
		return parseRequiredFloorModule(source);
	} catch (error) {
		if (error.code === "ENOENT") return { requiredOperations: [], requiredGates: [], requiredProjections: [] };
		throw error;
	}
}

export function findPreviousHistoricalRow(historyVersions, pinnedVersion) {
	const index = historyVersions.findIndex((entry) => entry.version === pinnedVersion);
	const previousEntry = index === -1 ? historyVersions[historyVersions.length - 1] : historyVersions[index - 1];
	return previousEntry?.capabilities;
}

async function buildGeneratedModule() {
	const snapshot = await readJson(SNAPSHOT_RELATIVE_PATH);
	const history = await readJson(HISTORY_RELATIVE_PATH);
	const lock = await readJson(LOCK_RELATIVE_PATH);
	const pinnedVersion = lock.release.version;

	const previousFloor = await readPreviousRequiredFloor();
	const requiredOperations = monotoneFloor(previousFloor.requiredOperations, snapshot.operations, "REQUIRED_OPERATIONS");
	const requiredGates = monotoneFloor(previousFloor.requiredGates, snapshot.gates, "REQUIRED_GATES");
	const requiredProjections = monotoneFloor(previousFloor.requiredProjections, snapshot.projections, "REQUIRED_PROJECTIONS");

	assertMandatoryFeaturesSupported(snapshot.features.mandatory.map((feature) => feature.name));

	const historicalRows = history.versions
		.filter((entry) => entry.version !== pinnedVersion)
		.map((entry) => ({ version: entry.version, row: { ...entry.capabilities, ...entry.envelopeFlags }, notes: entry.notes }));
	const pinnedEntry = history.versions.find((entry) => entry.version === pinnedVersion);
	const currentRow = deriveCapabilityRow({
		version: pinnedVersion,
		advertisedOperations: snapshot.operations,
		envelopeFlags: pinnedEntry?.envelopeFlags,
		previousRow: findPreviousHistoricalRow(history.versions, pinnedVersion),
		knownRow: pinnedEntry === undefined ? undefined : { ...pinnedEntry.capabilities, ...pinnedEntry.envelopeFlags },
	});

	return `${renderGeneratedFloorModule({
		requiredOperations,
		requiredGates,
		requiredProjections,
		historicalRows,
		currentVersion: pinnedVersion,
		currentRow,
		currentNotes: pinnedEntry?.notes,
	})}`;
}

async function main() {
	const mode = process.argv[2];
	if ((mode !== "--write" && mode !== "--check") || process.argv.length !== 3) {
		throw new Error("usage: build-gentle-ai-baselines.mjs --write|--check");
	}
	const expected = await buildGeneratedModule();
	assertNoTrailingWhitespace(expected, OUTPUT_RELATIVE_PATH);
	const destination = join(root, OUTPUT_RELATIVE_PATH);
	if (mode === "--write") {
		await writeFile(destination, expected, "utf8");
		process.stdout.write(`gentle-ai baselines generated (${OUTPUT_RELATIVE_PATH})\n`);
		return;
	}
	let actual;
	try {
		actual = await readFile(destination, "utf8");
	} catch {
		actual = undefined;
	}
	if (actual !== expected) {
		throw new Error(`generated gentle-ai baselines are stale: ${destination}`);
	}
	process.stdout.write(`gentle-ai baselines match their checked-in sources (${OUTPUT_RELATIVE_PATH})\n`);
}

const isMainModule = process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href;
if (isMainModule) {
	main().catch((error) => {
		process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
		process.exitCode = 1;
	});
}
